/**
 * /show —— 一个极简可视化：把 Slow Vale 的地图和角色渲染出来。
 *
 * ## 为什么不用它的 HUD
 *
 * HUD 的场景挂载依赖 scene_state/visual 管道（还没通），而"看见一个人在城里走"不该等那件事。
 * 这个页面只做三件事：画底图、按 Y 排序画物件、画人。用的资产、坐标、动画帧**全部来自 Slow Vale**，
 * 所以它不是另一套美术，是同一套东西的最小渲染器。
 *
 * 帧规格来自 PersonalityPicker.js 里的动画表：
 * walk = 第 2 行，方向块起点 right 0 / up 6 / left 12 / down 18，各 6 帧，帧 32×32。
 */
export function renderViewerHtml(): string {
  return [
    '<!doctype html>',
    '<html lang="zh-CN"><head><meta charset="utf-8" />',
    '<title>Slow Vale · 居民走动</title>',
    '<style>',
    'html,body{margin:0;height:100%;background:#101a24;overflow:hidden}',
    'canvas{display:block;image-rendering:pixelated}',
    '#hud{position:fixed;left:12px;top:10px;color:#f4ead5;font:12px/1.6 "Fusion Pixel 12px Proportional SC",monospace;',
    'background:rgba(26,29,46,.82);padding:8px 10px;box-shadow:0 0 0 2px #1a1d2e}',
    '#hud b{color:#ffd479}',
    '</style></head><body>',
    '<canvas id="c"></canvas>',
    '<div id="hud"><b id="who">…</b> <span id="where"></span><br><span id="pos"></span></div>',
    '<script>',
    'var SCALE = 2;',
    'var canvas = document.getElementById("c");',
    'var ctx = canvas.getContext("2d");',
    'ctx.imageSmoothingEnabled = false;',
    'var state = null, bg = null, objects = [], objImg = new Map(), placeSeq = -1;',
    'var DIR = { right: 0, up: 6, left: 12, down: 18 };',
    'var LOOK = {',
    '  body: "/assets/character_generator/bundles/base/Bodies/Body_32x32_01.png",',
    '  eyes: "/assets/character_generator/bundles/base/Eyes/Eyes_32x32_01.png",',
    '  outfit: "/assets/character_generator/bundles/base/Outfits/Outfit_01_32x32_01.png",',
    '  hair: "/assets/character_generator/bundles/base/Hairstyles/Hairstyle_01_32x32_01.png"',
    '};',
    'var layers = {};',
    'function loadImg(src) { return new Promise(function (resolve) {',
    '  var img = new Image(); img.onload = function () { resolve(img) }; img.onerror = function () { resolve(null) };',
    '  img.src = src; return img;',
    '}); }',
    'async function loadPlace(place) {',
    '  bg = await loadImg("/assets/maps/" + place + "/background.png");',
    '  objects = []; objImg.clear();',
    '  try {',
    '    var res = await fetch("/assets/maps/" + place + "/objects.json", { cache: "force-cache" });',
    '    var list = await res.json();',
    '    objects = list.filter(function (o) { return o && o.file });',
    '  } catch (e) { objects = [] }',
    '}',
    'function objectImg(file, place) {',
    '  var key = place + ":" + file;',
    '  if (!objImg.has(key)) {',
    '    objImg.set(key, null);',
    '    loadImg("/assets/maps/" + place + "/objects/" + file).then(function (img) { objImg.set(key, img) });',
    '  }',
    '  return objImg.get(key);',
    '}',
    'function frameRect(anim, dir, t) {',
    '  var block = DIR[dir] || 0;',
    '  var row = anim === "walk" ? 2 : 1;',
    '  var idx = block + Math.floor(t) % 6;',
    '  return { sx: idx * 32, sy: row * 32, w: 32, h: 32 };',
    '}',
    'function drawChar(cx, cy, dir, moving, t) {',
    '  var f = frameRect(moving ? "walk" : "idle", dir, moving ? t : 0);',
    '  var order = ["body", "eyes", "outfit", "hair"];',
    '  for (var i = 0; i < order.length; i += 1) {',
    '    var img = layers[order[i]];',
    '    if (!img) continue;',
    '    ctx.drawImage(img, f.sx, f.sy, f.w, f.h, cx - 16, cy - 32, 32, 32);',
    '  }',
    '}',
    'function draw(now) {',
    '  canvas.width = window.innerWidth; canvas.height = window.innerHeight;',
    '  ctx.imageSmoothingEnabled = false;',
    '  ctx.fillStyle = "#101a24"; ctx.fillRect(0, 0, canvas.width, canvas.height);',
    '  if (!state) return;',
    '  var W = bg ? bg.naturalWidth : 1920, H = bg ? bg.naturalHeight : 1080;',
    '  var camX = Math.max(0, Math.min(W - canvas.width / SCALE, state.x - canvas.width / (2 * SCALE)));',
    '  var camY = Math.max(0, Math.min(H - canvas.height / SCALE, state.y - canvas.height / (2 * SCALE)));',
    '  ctx.save(); ctx.scale(SCALE, SCALE); ctx.translate(-camX, -camY);',
    '  if (bg) ctx.drawImage(bg, 0, 0);',
    '  var drawables = objects.map(function (o) {',
    '    return { o: o, depth: o.y + (o.delta || 0) };',
    '  });',
    '  drawables.push({ char: true, depth: state.y });',
    '  drawables.sort(function (a, b) { return a.depth - b.depth });',
    '  for (var i = 0; i < drawables.length; i += 1) {',
    '    var d = drawables[i];',
    '    if (d.char) { drawChar(state.x, state.y, state.facing, state.moving, (now / 120) % 6); continue }',
    '    var o = d.o;',
    '    if (o.x + o.width < camX - 64 || o.x > camX + canvas.width / SCALE + 64) continue;',
    '    var img = objectImg(o.file, state.placeAsset || state.place);',
    '    if (img) ctx.drawImage(img, o.x, o.y - img.naturalHeight);',
    '  }',
    '  ctx.restore();',
    '}',
    'async function sync() {',
    '  try {',
    '    var res = await fetch("/api/show/state", { cache: "no-store" });',
    '    state = await res.json();',
    '    if (state.placeSeq !== placeSeq) {',
    '      placeSeq = state.placeSeq;',
    '      await loadPlace(state.placeAsset || state.place);',
    '    }',
    '    document.getElementById("who").textContent = state.name;',
    '    document.getElementById("where").textContent = state.placeLabel;',
    '    document.getElementById("pos").textContent = Math.round(state.x) + ", " + Math.round(state.y) + (state.moving ? " · 行走中" : " · 停留");',
    '  } catch (e) {}',
    '}',
    'async function boot() {',
    '  await Promise.all(Object.keys(LOOK).map(function (k) {',
    '    return loadImg(LOOK[k]).then(function (img) { layers[k] = img })',
    '  }));',
    '  await sync();',
    '  setInterval(sync, 150);',
    '  setInterval(function () { draw(performance.now()) }, 33);',
    '}',
    'boot();',
    '</script></body></html>',
  ].join('')
}
